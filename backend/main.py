import os
import sys
import subprocess
import webbrowser
import joblib
import numpy as np
from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field

# ============================================================
# APP INITIALIZATION
# ============================================================

app = FastAPI(
    title="Customer Segmentation API",
    description="Serves predictions from a pretrained Random Forest model.",
    version="1.0.0"
)

# Allow the Streamlit frontend (and local dev tools) to call this API.
# Update allow_origins with your deployed frontend URL in production.
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],          # tighten this in production, e.g. ["http://localhost:8501"]
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# ============================================================
# PATHS & FEATURE ORDER
# ============================================================

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
MODEL_PATH = os.path.join(BASE_DIR, "models", "random_forest.pkl")
SCALER_PATH = os.path.join(BASE_DIR, "models", "scaler.pkl")
KMEANS_PATH = os.path.join(BASE_DIR, "models", "kmeans.pkl")
FEATURES_PATH = os.path.join(BASE_DIR, "models", "model_features.pkl")


FEATURES = [
    "Recency",
    "Frequency",
    "Monetary",
    "Avg_Discount_Rate",
    "Unique_Product_Categories",
    "Total_Profit",
]

SEGMENT_INFO = {
    0: {
        "name": "Regular Mid-Value Customers",
        "description": "Customers with moderate purchase frequency and spending.",
        "action": "Encourage repeat purchases with personalized recommendations."
    },
    1: {
        "name": "New / Discount-Sensitive Customers",
        "description": "Recently active customers with low spending and higher discount usage.",
        "action": "Test targeted offers and encourage a second purchase."
    },
    2: {
        "name": "High-Value Profitable Customers",
        "description": "Frequent customers with the highest spending and profit.",
        "action": "Reward loyalty and recommend complementary products."
    },
    3: {
        "name": "At-Risk / Inactive Customers",
        "description": "Customers with the longest time since their last purchase.",
        "action": "Use win-back campaigns and personalized re-engagement offers."
    },
    4: {
        "name": "Recent Low-Value Customers",
        "description": "Recently active customers with low purchase frequency and spending.",
        "action": "Encourage a second purchase through relevant recommendations."
    }
}
# ============================================================
# LOAD MODEL & SCALER (ONCE, AT STARTUP)
# ============================================================

model = None
scaler = None
kmeans = None
FEATURES = None
load_error = None

try:
    model = joblib.load(MODEL_PATH)
    scaler = joblib.load(SCALER_PATH)
    kmeans = joblib.load(KMEANS_PATH)
    FEATURES = joblib.load(FEATURES_PATH)

    if len(FEATURES) != 6:
        raise ValueError(
            f"Expected 6 model features, got {len(FEATURES)}"
        )

except Exception as e:
    load_error = str(e)



# ============================================================
# REQUEST / RESPONSE SCHEMAS
# ============================================================

class CustomerInput(BaseModel):
    Recency: float = Field(..., ge=0, description="Days since last purchase")
    Frequency: float = Field(..., ge=0, description="Number of purchases made")
    Monetary: float = Field(..., ge=0, description="Total spending amount")
    Avg_Discount_Rate: float = Field(..., ge=0, le=1, description="Average discount rate, 0-1")
    Unique_Product_Categories: float = Field(..., ge=0, description="Number of distinct categories purchased")
    Total_Profit: float = Field(..., description="Total profit generated by the customer")

    class Config:
        json_schema_extra = {
            "example": {
                "Recency": 100.0,
                "Frequency": 2.0,
                "Monetary": 500.0,
                "Avg_Discount_Rate": 0.10,
                "Unique_Product_Categories": 2.0,
                "Total_Profit": 100.0,
            }
        }


class PredictionResponse(BaseModel):
    cluster: int
    segment_name: str
    description: str
    recommendation: str


class HealthResponse(BaseModel):
    status: str
    model_loaded: bool
    scaler_loaded: bool
    detail: str | None = None


# ============================================================
# ENDPOINTS
# ============================================================

@app.get("/health", response_model=HealthResponse)
def health_check():
    """Simple readiness check for the API and its model artifacts."""
    ok = model is not None and scaler is not None and FEATURES is not None
    return HealthResponse(
        status="ok" if ok else "error",
        model_loaded=model is not None,
        scaler_loaded=scaler is not None,
        detail=load_error if not ok else None,
    )


@app.post("/predict", response_model=PredictionResponse)
def predict(customer: CustomerInput):
    """Predict a customer's segment from their RFM + behavioral features."""

    if model is None or scaler is None or FEATURES is None:
        raise HTTPException(
            status_code=503,
            detail=f"Model artifacts not loaded: {load_error}",
        )

    try:
        # Build input in the exact feature order saved with the trained model.
        input_values = {
            "Recency": customer.Recency,
            "Frequency": customer.Frequency,
            "Monetary": customer.Monetary,
            "Avg_Discount_Rate": customer.Avg_Discount_Rate,
            "Unique_Product_Categories": customer.Unique_Product_Categories,
            "Total_Profit": customer.Total_Profit,
        }
        input_array = np.array([[input_values[feature] for feature in FEATURES]], dtype=float)

        # This must match the preprocessing used to train the saved Random Forest.
        input_scaled = scaler.transform(input_array)
        prediction = model.predict(input_scaled)
        cluster = int(prediction[0])

        segment = SEGMENT_INFO.get(cluster)
        if segment is None:
            raise HTTPException(
                status_code=500,
                detail=f"Model returned an unknown cluster id: {cluster}",
            )

        return PredictionResponse(
            cluster=cluster,
            segment_name=segment["name"],
            description=segment["description"],
            recommendation=segment["action"],
        )

    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Prediction failed: {str(e)}")


@app.get("/")
def root():
    return {"message": "Customer Segmentation API is running. See /docs for API documentation."}


# ============================================================
# AUTO-LAUNCH STREAMLIT FRONTEND
# ============================================================
# Starts the Streamlit app as a subprocess when the API starts,
# so `uvicorn main:app --reload --port 8000` brings up both
# the backend and the frontend together.

STREAMLIT_PORT = 8501
FRONTEND_APP_PATH = os.path.join(BASE_DIR, "..", "frontend", "app.py")

streamlit_process = None


def _port_in_use(port: int) -> bool:
    import socket
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        return s.connect_ex(("127.0.0.1", port)) == 0


@app.on_event("startup")
def launch_streamlit():
    global streamlit_process

    if _port_in_use(STREAMLIT_PORT):
        print(
            f"[info] Streamlit already running "
            f"on port {STREAMLIT_PORT}"
        )
        return

    if not os.path.exists(FRONTEND_APP_PATH):
        print(f"[warning] Frontend app not found at {FRONTEND_APP_PATH}, skipping auto-launch.")
        return

    streamlit_process = subprocess.Popen(
        [
            sys.executable,
            "-m",
            "streamlit",
            "run",
            FRONTEND_APP_PATH,
            "--server.address",
            "0.0.0.0",
            "--server.port",
            str(STREAMLIT_PORT),
            "--server.headless",
            "true",
            "--browser.gatherUsageStats",
            "false",
        ]
    )
    print(f"[info] Streamlit frontend starting at http://127.0.0.1:{STREAMLIT_PORT}")


@app.on_event("shutdown")
def stop_streamlit():
    global streamlit_process
    if streamlit_process is not None and streamlit_process.poll() is None:
        streamlit_process.terminate()
        try:
            streamlit_process.wait(timeout=5)
        except subprocess.TimeoutExpired:
            streamlit_process.kill()

